#!/usr/bin/env python3
"""summarize.py - turn results/E*.csv into report tables (Markdown).

Every cell is "median [min-max]" over the repeated runs of one
configuration, as Section 4.1 requires.  Standard library only.

usage: python3 scripts/summarize.py [results_dir] > results/summary.md
"""
import csv
import os
import statistics
import sys

# columns shown for each experiment: (csv column, heading with unit)
COLUMNS = {
    "E1": [("lost", "lost"), ("duplicated", "duplicated"),
           ("violations", "violations"), ("elapsed_s", "elapsed (s)")],
    "E2": [("throughput_ops_s", "throughput (patients/s)"),
           ("amb_blocked_ms", "ambulances blocked (ms)"),
           ("avg_wait_ms", "avg wait (ms)")],
    "E3": [("wait_sev1_ms", "avg sev1 (ms)"), ("max_sev1_ms", "max sev1 (ms)"),
           ("wait_sev2_ms", "avg sev2 (ms)"), ("max_sev2_ms", "max sev2 (ms)"),
           ("wait_sev3_ms", "avg sev3 (ms)"), ("max_sev3_ms", "max sev3 (ms)"),
           ("doctor_util", "doctor util")],
    "E4": [("wait_sev1_ms", "avg sev1 (ms)"), ("max_sev1_ms", "max sev1 (ms)"),
           ("wait_sev2_ms", "avg sev2 (ms)"), ("max_sev2_ms", "max sev2 (ms)"),
           ("wait_sev3_ms", "avg sev3 (ms)"), ("max_sev3_ms", "max sev3 (ms)")],
    "E5": [("throughput_ops_s", "throughput (patients/s)"),
           ("avg_wait_ms", "avg wait (ms)"), ("max_wait_ms", "max wait (ms)"),
           ("sem_ops_per_item", "sem ops / patient"),
           ("elapsed_s", "elapsed (s)")],
}
COLUMNS["E4_aging"] = COLUMNS["E4"] + [("promoted", "promoted")]


def fmt(values):
    med = statistics.median(values)
    lo, hi = min(values), max(values)
    def f(x):
        return f"{x:.0f}" if abs(x) >= 100 else f"{x:.3g}" if x else "0"
    return f"{f(med)} [{f(lo)}–{f(hi)}]"


def table(path, exp):
    with open(path, newline="") as fh:
        rows = list(csv.DictReader(fh))
    if not rows:
        return
    groups = {}                       # keep first-seen order
    for r in rows:
        groups.setdefault((r["mode"], r["param_name"], r["param_value"]),
                          []).append(r)
    cols = COLUMNS.get(exp, COLUMNS["E5"])
    print(f"\n### {exp} ({len(rows)} runs, cells = median [min–max])\n")
    print("| mode | parameter | runs | " +
          " | ".join(h for _, h in cols) + " |")
    print("|" + "---|" * (3 + len(cols)))
    for (mode, pname, pval), rs in groups.items():
        cells = [fmt([float(r[c]) for r in rs]) for c, _ in cols]
        print(f"| {mode} | {pname}={pval} | {len(rs)} | " +
              " | ".join(cells) + " |")


def main():
    d = sys.argv[1] if len(sys.argv) > 1 else "results"
    print("# Experiment results (generated by scripts/summarize.py)")
    m = os.path.join(d, "machine.txt")
    if os.path.exists(m):
        print("\n```\n" + open(m).read().strip() + "\n```")
    for exp in ["E1", "E2", "E3", "E4", "E4_aging", "E5"]:
        p = os.path.join(d, exp + ".csv")
        if os.path.exists(p):
            table(p, exp)
    loc = os.path.join(d, "E5_loc.txt")
    if os.path.exists(loc):
        print("\n### E5 lines of code\n\n```\n" + open(loc).read().strip() +
              "\n```")


if __name__ == "__main__":
    main()
